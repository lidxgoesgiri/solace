// Generates src/components/icons/<name>.tsx from Lucide's icon data (ISC licence).
// Solace renders the few icons it needs as plain SVG components instead of
// shipping lucide-react's runtime on every page (PRD 14: initial JS budget).
//
// Usage: add the Lucide name (kebab-case) to ICONS, then `pnpm ui-icons`.
// The lucide-static package provides the path data as a dev dependency.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const ICONS = [
  "arrow-left",
  "arrow-right",
  "book-open",
  "calendar-clock",
  "chart-line",
  "check",
  "circle-alert",
  "clipboard-list",
  "coffee",
  "download",
  "ear",
  "external-link",
  "eye",
  "eye-off",
  "file-text",
  "flower-2",
  "hand",
  "heart-handshake",
  "info",
  "key-round",
  "languages",
  "life-buoy",
  "lock",
  "log-in",
  "log-out",
  "mail-x",
  "notebook-pen",
  "moon",
  "pause",
  "phone",
  "rotate-ccw-clock",
  "save",
  "shield-check",
  "sparkles",
  "sun",
  "trash",
  "upload",
  "user-round",
  "user-round-x",
  "wind",
  "x",
];

const require = createRequire(import.meta.url);
const lucideRoot = dirname(require.resolve("lucide-static/package.json"));
const iconNodes = JSON.parse(readFileSync(join(lucideRoot, "icon-nodes.json"), "utf8"));
const licence = readFileSync(join(lucideRoot, "LICENSE"), "utf8").split("\n")[2] ?? "";

const pascal = (name) =>
  name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const attr = (key) => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const header = [
  "// Generated by scripts/generate-ui-icons.mjs. Do not edit by hand.",
  `// Icon shape from Lucide (https://lucide.dev), ISC licence. ${licence.trim()}`,
];

const outDir = new URL("../src/components/icons/", import.meta.url);
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// One file per icon: the bundler then ships only the icons a page imports.
writeFileSync(
  new URL("svg.tsx", outDir),
  [
    ...header.slice(0, 1),
    "",
    'import type { SVGProps } from "react";',
    "",
    "export type IconProps = SVGProps<SVGSVGElement>;",
    "",
    "export function Svg({ children, ...props }: IconProps) {",
    "  return (",
    "    <svg",
    '      xmlns="http://www.w3.org/2000/svg"',
    "      width={24}",
    "      height={24}",
    '      viewBox="0 0 24 24"',
    '      fill="none"',
    '      stroke="currentColor"',
    "      strokeWidth={2}",
    '      strokeLinecap="round"',
    '      strokeLinejoin="round"',
    "      {...props}",
    "    >",
    "      {children}",
    "    </svg>",
    "  );",
    "}",
    "",
  ].join("\n"),
);

for (const name of ICONS) {
  const node = iconNodes[name];
  if (!node) throw new Error(`Unknown Lucide icon: ${name}`);
  const children = node
    .map(([tag, attrs]) => {
      const props = Object.entries(attrs)
        .filter(([key]) => key !== "key")
        .map(([key, value]) => `${attr(key)}="${value}"`)
        .join(" ");
      return `      <${tag} ${props} />`;
    })
    .join("\n");
  const file = [
    ...header,
    "",
    'import { Svg, type IconProps } from "./svg";',
    "",
    `export function ${pascal(name)}(props: IconProps) {`,
    "  return (",
    "    <Svg {...props}>",
    children,
    "    </Svg>",
    "  );",
    "}",
    "",
  ].join("\n");
  writeFileSync(new URL(`${name}.tsx`, outDir), file);
}

console.log(`Wrote ${ICONS.length} icons to src/components/icons/`);
