// Bakes the fonts and logo used by the PDF report into a TypeScript module,
// so building the PDF needs no network request (PRD 12, PDF-01).
// Run with: pnpm report-assets
//
// Sources:
//   @fontsource/inter  (Inter 400 and 600, latin, WOFF)  SIL Open Font License 1.1
//   @fontsource/lora   (Lora 600, latin, WOFF)           SIL Open Font License 1.1
//   public/brand/logo.png (resized; shapes untouched)
//
// WOFF is used because @pdf-lib/fontkit cannot subset WOFF2.

import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fontsource = (pkg, file) => path.join(root, "node_modules", "@fontsource", pkg, "files", file);
const outDir = path.join(root, "src", "lib", "report");

async function base64(file) {
  return (await readFile(file)).toString("base64");
}

async function main() {
  const logo = await sharp(path.join(root, "public", "brand", "logo.png"))
    .resize({ width: 144 })
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();

  const assets = {
    INTER_REGULAR: await base64(fontsource("inter", "inter-latin-400-normal.woff")),
    INTER_SEMIBOLD: await base64(fontsource("inter", "inter-latin-600-normal.woff")),
    LORA_SEMIBOLD: await base64(fontsource("lora", "lora-latin-600-normal.woff")),
    LOGO_PNG: logo.toString("base64"),
  };

  const lines = [
    "// Generated by scripts/generate-report-assets.mjs (pnpm report-assets). Do not edit.",
    "// Inter and Lora are licensed under the SIL Open Font License 1.1; see ./licenses.",
    "// Bundled as base64 so that creating the PDF makes no network request (PDF-01).",
    "",
    ...Object.entries(assets).map(([name, value]) => `export const ${name} =\n  "${value}";\n`),
  ];
  await writeFile(path.join(outDir, "assets.ts"), lines.join("\n"));

  await mkdir(path.join(outDir, "licenses"), { recursive: true });
  await copyFile(
    path.join(root, "node_modules", "@fontsource", "inter", "LICENSE"),
    path.join(outDir, "licenses", "Inter-OFL.txt"),
  );
  await copyFile(
    path.join(root, "node_modules", "@fontsource", "lora", "LICENSE"),
    path.join(outDir, "licenses", "Lora-OFL.txt"),
  );

  console.log("Report assets generated.");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
